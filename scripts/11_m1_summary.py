"""Stage 11: collect milestone 1 numbers into docs/m1_results.md."""
import json

import pandas as pd

from pafbench.config import OUT, REPO
from pafbench.molecules import beyond_cap
from pafbench.report import parse_gnu_time, time_row


def _j(p):
    return json.loads(p.read_text()) if p.exists() else None


def main():
    lines = ["# Milestone 1 results (generated by scripts/11_m1_summary.py)", ""]
    lines += ["## Original polyAfilter on 1417", "", "| Step | Wall time (h) | Max RSS (GiB, largest single process) | Exit |", "|---|---|---|---|"]
    for p in sorted((OUT / "1417" / "original").glob("*.time.txt")) + [OUT / "ref" / "createDB.time.txt"]:
        if p.exists():
            t = parse_gnu_time(p)
            lines.append(time_row(p.name.replace('.time.txt', ''), t))
    lines += ["", "Peak RSS is the largest single process; runs with -p 8 used more memory in total."]
    em = _j(OUT / "1417" / "exact_match.json") or {}
    lines += ["", "## Exact match, 1417", "", "| Setting | Original removed | Reimpl removed | Only original | Only reimpl | Identical |", "|---|---|---|---|---|---|"]
    for tag, r in em.items():
        lines.append(f"| {tag} | {r['n_original']:,} | {r['n_reimpl']:,} | {r['only_original']:,} | {r['only_reimpl']:,} | {r['identical']} |")
    coll = _j(OUT / "1417" / "collisions.json") or {}
    cut = _j(OUT / "1417" / "label_cutoffs.json") or {}
    scope = _j(OUT / "scope_check.json") or {}
    tags = _j(OUT / "1417" / "spikein" / "tag_check.json") or {}
    bd = {name: _j(OUT / name / "ends_check.json") or {} for name in ("BD67", "BD70")}
    ub = _j(OUT / "1179" / "ub_on_introns.json") or {}
    members = pd.read_parquet(OUT / "1417" / "members.parquet")
    bc = beyond_cap(members)
    lines += ["", "## Truth set, 1417", "",
              f"- Molecules: {coll.get('molecules')}; member reads: {coll.get('members')}",
              "- Member cap: fixed 1,000 nt of exon-aware distance (user decision); sensitivity at 500 and 2,000 nt",
              f"- Members beyond the cap (population of {bc['population']} candidate members with dist3_exon >= -25): "
              f"500 nt: {bc['500']['members']} members in {bc['500']['molecules']} molecules; "
              f"1,000 nt: {bc['1000']['members']} members in {bc['1000']['molecules']} molecules; "
              f"2,000 nt: {bc['2000']['members']} members in {bc['2000']['molecules']} molecules",
              f"- Density-based cap rule (dropped): genomic {coll.get('cap')}, exon-aware {coll.get('exon_aware', {}).get('cap')}",
              f"- Collision background per bp: other chromosomes {coll.get('background_other_refs_per_bp')}, far same chromosome {coll.get('background_far_same_ref_per_bp')}",
              f"- Exon-aware member distance: members by distance mode {coll.get('exon_aware', {}).get('mode_counts')}",
              f"- Label cut-offs: templated at A >= {cut.get('templated_min')}, non-templated at A <= {cut.get('nontemplated_max')} (tail rate {cut.get('tail_rate')}, background {cut.get('background_rate')})",
              "", "## Scope check (1416 vs 1417, chr1)", "", f"- go: {scope.get('go')}; molecules: {scope.get('molecules')}",
              "", "## Spike-in tags (1417)", "", f"- {json.dumps(tags.get('survival'))}; modules: {tags.get('modules')}",
              "", "## Long-read ends (BD67, BD70)", ""] + [f"- {name}: {json.dumps({k: d.get(k) for k in ('reads', 'frac_clip_a_ge10', 'ratio_nontempl_templ', 'accept')})}" for name, d in bd.items()] + [
              "", "## UB on reads in 1179 (chr1)", "", f"- {json.dumps(ub)}"]
    out = REPO / "docs" / "m1_results.md"
    out.write_text("\n".join(lines) + "\n")
    print(out)


if __name__ == "__main__":
    main()
